"""Draws TranslatorAI's launcher icon: a vector adaptive icon (Android 8+) and
PNGs for older versions, from one set of shapes on Android's 108-unit canvas.
Stdlib only: a tiny supersampling rasterizer writes the PNGs."""
import os, struct, sys, zlib

RES = sys.argv[1]
BG = (0x2E, 0x7D, 0x6B)
BACK = (0xA7, 0xE0, 0xD1)
FRONT = (0xFF, 0xFF, 0xFF)
DOT = BG

def rrect(x0, y0, x1, y1, r): return ('rrect', x0, y0, x1, y1, r)
def tri(*p): return ('tri', p)
def circle(cx, cy, r): return ('circle', cx, cy, r)

# painter's order: (colour, [shapes forming one region])
LAYERS = [
    (BACK, [rrect(44, 42, 84, 72, 9), tri((70, 70), (80, 70), (83, 82))]),
    (BG, [rrect(50, 64.5, 76, 67, 1.25), rrect(71, 51.5, 79, 54, 1.25)]),
    (FRONT, [rrect(26, 30, 68, 60, 9), tri((32, 58), (44, 58), (29, 70))]),
    (DOT, [circle(36, 45, 3.2), circle(47, 45, 3.2), circle(58, 45, 3.2)]),
]

def inside(sh, x, y):
    k = sh[0]
    if k == 'rrect':
        _, x0, y0, x1, y1, r = sh
        if x < x0 or x > x1 or y < y0 or y > y1: return False
        cx = min(max(x, x0 + r), x1 - r); cy = min(max(y, y0 + r), y1 - r)
        return (x - cx) ** 2 + (y - cy) ** 2 <= r * r
    if k == 'circle':
        _, cx, cy, r = sh
        return (x - cx) ** 2 + (y - cy) ** 2 <= r * r
    (ax, ay), (bx, by), (qx, qy) = sh[1]
    d1 = (x - bx) * (ay - by) - (ax - bx) * (y - by)
    d2 = (x - qx) * (by - qy) - (bx - qx) * (y - qy)
    d3 = (x - ax) * (qy - ay) - (qx - ax) * (y - ay)
    neg = d1 < 0 or d2 < 0 or d3 < 0; pos = d1 > 0 or d2 > 0 or d3 > 0
    return not (neg and pos)

def png(path, size, legacy_bg=True, ss=4):
    rows = []
    scale = 108 / size
    for py in range(size):
        row = bytearray([0])
        for px in range(size):
            acc = [0, 0, 0, 0]
            for sy in range(ss):
                for sx in range(ss):
                    x = (px + (sx + .5) / ss) * scale; y = (py + (sy + .5) / ss) * scale
                    col = None
                    if legacy_bg and inside(rrect(4, 4, 104, 104, 24), x, y): col = BG
                    for c, shapes in LAYERS:
                        if any(inside(s, x, y) for s in shapes): col = c
                    if col:
                        acc[0] += col[0]; acc[1] += col[1]; acc[2] += col[2]; acc[3] += 255
            n = ss * ss; a = acc[3] / n
            if a: row += bytes([round(acc[0] / (acc[3] / 255)), round(acc[1] / (acc[3] / 255)), round(acc[2] / (acc[3] / 255)), round(a)])
            else: row += bytes(4)
        rows.append(bytes(row))
    def chunk(t, d): return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0)) \
        + chunk(b'IDAT', zlib.compress(b''.join(rows), 9)) + chunk(b'IEND', b'')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'wb').write(data)

def vpath(sh):
    k = sh[0]
    f = lambda v: ('%.2f' % v).rstrip('0').rstrip('.')
    if k == 'rrect':
        _, x0, y0, x1, y1, r = sh
        w = x1 - x0 - 2 * r; h = y1 - y0 - 2 * r
        return (f'M{f(x0 + r)},{f(y0)}h{f(w)}a{f(r)},{f(r)} 0 0 1 {f(r)},{f(r)}v{f(h)}a{f(r)},{f(r)} 0 0 1 {f(-r)},{f(r)}'
                f'h{f(-w)}a{f(r)},{f(r)} 0 0 1 {f(-r)},{f(-r)}v{f(-h)}a{f(r)},{f(r)} 0 0 1 {f(r)},{f(-r)}z')
    if k == 'circle':
        _, cx, cy, r = sh
        return f'M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1 0 {f(2 * r)},0a{f(r)},{f(r)} 0 1 0 {f(-2 * r)},0z'
    (a, b, c) = sh[1]
    return f'M{f(a[0])},{f(a[1])}L{f(b[0])},{f(b[1])}L{f(c[0])},{f(c[1])}z'

hexc = lambda c: '#FF%02X%02X%02X' % c
paths = '\n'.join(f'    <path android:fillColor="{hexc(c)}" android:pathData="{"".join(vpath(s) for s in shapes)}"/>' for c, shapes in LAYERS)
os.makedirs(f'{RES}/drawable', exist_ok=True)
open(f'{RES}/drawable/ic_launcher_foreground.xml', 'w').write(
    '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by make_icon.py: two speech bubbles -->\n'
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp" android:height="108dp"\n'
    '    android:viewportWidth="108" android:viewportHeight="108">\n' + paths + '\n</vector>\n')
os.makedirs(f'{RES}/mipmap-anydpi-v26', exist_ok=True)
open(f'{RES}/mipmap-anydpi-v26/ic_launcher.xml', 'w').write(
    '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
    '    <background android:drawable="@color/ic_launcher_background"/>\n'
    '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
    '    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>\n</adaptive-icon>\n')
open(f'{RES}/values/ic_launcher_background.xml', 'w').write(
    '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#2E7D6B</color>\n</resources>\n')
for d, n in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
    png(f'{RES}/mipmap-{d}/ic_launcher.png', n)
png(sys.argv[2], 512) if len(sys.argv) > 2 else None
print('icon written')
